'use strict';
const assert = require('node:assert/strict');
const test = require('node:test');
const { fixture, client } = require('./helpers/retest7-session.cjs');

for (const transition of ['account A to B', 'same user replacement', 'account A to B to A']) {
  for (const outcome of [200, 401, 500, 'network']) {
    test(`R7-HIST-01: ${transition} via real OAuth and Refresh discards held ${outcome}`, { timeout: 15000 }, async t => {
      const server = await fixture(t); await server.login('User-A'); const app = await client(server);
      assert.equal(app.snapshot().status.authenticated, true);
      assert.equal(app.snapshot().calls.length, 4);
      const held = app.hold('/api/transcripts/old-', outcome);
      const copy = app.run("copyCallPart('old-call','transcript')").then(value => ({ value }), error => ({ error: error.message }));
      assert.equal((await held.started.promise).status, 200, 'Held response is generated by real synthetic OAuth/provider HTTP');
      if (transition === 'same user replacement') await server.login('User-A');
      else { await server.login('User-B'); if (transition.endsWith('to A')) await server.login('User-A'); }
      await app.refresh();
      // Fill the NEW session cache through the real copy action, never a state setter.
      assert.equal(await app.run("copyCallPart('current-call','transcript')"), true);
      const before = app.snapshot(), clipboard = [...app.clipboard];
      held.release.resolve(); const result = await copy; const after = app.snapshot();
      assert.deepEqual({ result, clipboard: app.clipboard, authenticated: after.status.authenticated,
        account: after.status.account, cache: after.cache },
      { result: { value: false }, clipboard, authenticated: true, account: before.status.account, cache: before.cache },
      'An accepted replacement must invalidate old content, auth mutations and action errors');
    });
  }
}

for (const transition of ['demo', 'logout']) for (const outcome of [200, 401, 500, 'network']) {
  test(`R7-HIST-01 control: actual ${transition} control cancels held ${outcome}`, { timeout: 15000 }, async t => {
    const server = await fixture(t); await server.login('User-A'); const app = await client(server);
    const held = app.hold('/api/transcripts/old-', outcome);
    const copy = app.run("copyCallPart('old-call','transcript')").then(value => ({ value }), error => ({ error: error.message }));
    await held.started.promise;
    // The old fetch is deliberately pending; these controls themselves are synchronous
    // event entry points, so wait for their *new* status/list rather than all fetches.
    const action = transition === 'demo' ? app.demo(true) : app.logout();
    const { until } = require('./helpers/retest7-session.cjs');
    await until(() => transition === 'demo' ? app.snapshot().calls[0]?.source === 'demo' : app.snapshot().status.authenticated === false);
    await action; const before = app.snapshot(); held.release.resolve();
    assert.deepEqual(await copy, { value: false }); assert.deepEqual(app.clipboard, []);
    assert.deepEqual(app.snapshot().cache, before.cache);
  });
}

