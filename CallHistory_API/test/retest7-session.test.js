test('R7-HIST-01: delayed browser-settings response cannot clear the newer accepted session/cache', async t => {
  const server = await fixture(t); await server.login('User-A'); const app = await client(server);
  const held = app.hold('/api/settings/browser-login', 200);
  const old = app.run("submitCallHistoryBrowserLogin({fields:{clientId:'synthetic-client'}})");
  const response = await held.started.promise; assert.equal(response.status, 200);
  assert.equal(JSON.parse(response.body).status.authenticated, false, 'The real settings endpoint invalidated A');
  await server.login('User-B'); await app.refresh(); await app.run("copyCallPart('current-call','transcript')");
  const before = app.snapshot();
  // Hold the following status refresh too, so a stale intermediate assignment
  // cannot hide behind an immediately succeeding corrective HTTP response.
  const next = app.hold('/api/status', 200); held.release.resolve(); await Promise.race([next.started.promise, old]);
  const during = app.snapshot(); next.release.resolve(); await old;
  assert.deepEqual({ status: during.status, cache: during.cache }, { status: before.status, cache: before.cache });
});
