#!/usr/bin/env python3
"""Build the offline PDF font asset from the existing licensed brand font.

Development only: python -m pip install 'fonttools[woff]==4.60.1'
Then run this script, or pass --check to verify the committed output.
No font download and no runtime Python dependency are involved.
"""

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path

import fontTools
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared/assets/fonts/PPPangramSans-Variable.woff2"
OUTPUT = ROOT / "Portal_API/public/pdf/pangram-font.js"
FONTTOOLS_VERSION = "4.60.1"


def build():
    if fontTools.__version__ != FONTTOOLS_VERSION:
        raise SystemExit(f"Use fonttools[woff]=={FONTTOOLS_VERSION} for a reproducible font build.")
    source_bytes = SOURCE.read_bytes()
    font = TTFont(io.BytesIO(source_bytes), recalcTimestamp=False)
    source_cmap = font.getBestCmap()
    embedding = font["OS/2"].fsType
    # Restricted-license and bitmap-only embedding cannot be used for this export.
    # The project-supplied asset currently declares editable embedding (0x0008).
    if embedding & (0x0002 | 0x0200):
        raise SystemExit("The supplied font does not permit the required outline embedding.")
    axes = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
    axes["wght"] = 400
    font = instantiateVariableFont(font, axes, inplace=True, optimize=True)
    font.flavor = None
    font.recalcTimestamp = False
    if "fvar" in font or "glyf" not in font:
        raise SystemExit("Expected a static TrueType outline font after instancing.")
    if font.getBestCmap() != source_cmap:
        raise SystemExit("Font conversion must retain the complete source character map.")
    buffer = io.BytesIO()
    font.save(buffer, reorderTables=True)
    font_bytes = buffer.getvalue()
    asset = {
        "fileName": "PangramSans-Regular.ttf",
        "family": "PangramSans",
        "style": "normal",
        "data": base64.b64encode(font_bytes).decode("ascii"),
    }
    header = (
        "// Generated by scripts/build-portal-pdf-font.py; do not edit.\n"
        "// Proprietary, owner-supplied licensed Pangram font. See THIRD_PARTY.md.\n"
        f"// Source SHA-256: {hashlib.sha256(source_bytes).hexdigest()}\n"
        f"// Static TTF SHA-256: {hashlib.sha256(font_bytes).hexdigest()}\n"
        f"// fontTools {FONTTOOLS_VERSION}; axes {json.dumps(axes, sort_keys=True)}; "
        f"OS/2 fsType={embedding}; all {len(source_cmap)} mapped characters retained.\n"
    )
    # A script asset works under file:// as well as HTTP; no font fetch is needed.
    return header + "window.NfonPdfFont = Object.freeze(" + json.dumps(asset, separators=(",", ":")) + ");\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("PDF font asset is out of date; run scripts/build-portal-pdf-font.py.")
        print("Verified offline PDF font asset.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Built {OUTPUT.relative_to(ROOT)} ({len(expected.encode('utf-8'))} bytes).")


if __name__ == "__main__":
    main()
