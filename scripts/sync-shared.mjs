import { readFile, writeFile, mkdir, rename, rm, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const checkOnly = process.argv.includes('--check');
const writes = [];
const orphans = [];
const targets = ['CTI_API/public', 'Portal_API/public', 'CallHistory_API/public', 'landing/public', 'docs'];
const catalogs = ['shared', 'CTI_API', 'Portal_API', 'CallHistory_API', 'landing', 'docs'];
const languages = ['en', 'de', 'fr', 'es', 'it', 'nl', 'pl', 'pt', 'sv', 'da', 'fi', 'cs'];
const messages = {};
const byCatalog = {};
for (const directory of catalogs) {
  // Every shipped application and the static demo require their catalogue.
  // Missing source is an invalid tree, never an implicit request to drop keys.
  const catalog = JSON.parse(await readFile(path.join(root, directory, 'i18n-messages.json'), 'utf8'));
  if (catalog === null || typeof catalog !== 'object' || Array.isArray(catalog)) {
    throw new Error(`${directory}/i18n-messages.json must be a JSON object mapping message keys to translations`);
  }
  byCatalog[directory] = catalog;
  for (const [key, values] of Object.entries(catalog)) {
    if (Object.hasOwn(messages, key)) throw new Error(`Duplicate message key: ${key}`);
    const parameters = (text) => [...new Set([...text.matchAll(/\{([A-Za-z][\w]*)\}/g)].map((match) => match[1]))].sort().join(',');
    for (const language of languages) {
      if (typeof values?.[language] !== 'string' || !values[language].trim()) {
        throw new Error(`Missing or invalid ${language} translation: ${key}`);
      }
      if (parameters(values.en) !== parameters(values[language])) throw new Error(`Mismatched message parameters: ${key} (${language})`);
    }
    messages[key] = values;
  }
}
function generated(app) {
  const scoped = { ...byCatalog.shared, ...byCatalog[app], ...byCatalog.docs };
  return `// Generated by scripts/sync-shared.mjs. Edit the app message catalogs.\nwindow.NFON_MESSAGES = ${JSON.stringify(scoped, null, 2)};\n`;
}
const i18n = await readFile(path.join(root, 'docs/i18n.js'));
const demoRuntime = await readFile(path.join(root, 'docs/demo-runtime.js'));
async function emit(file, content) {
  const expected = Buffer.from(content);
  const actual = await readFile(file).catch((error) => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (actual?.equals(expected)) return;
  if (checkOnly) throw new Error(`Shared asset out of sync: ${path.relative(root, file)}`);
  writes.push({ file, expected });
}
await emit(path.join(root, 'CTI_API/public/demo-runtime.js'), demoRuntime);
for (const target of targets) {
  const directory = path.join(root, target);
  await emit(path.join(directory, 'messages.js'), generated(target === 'docs' ? 'landing' : target.split('/')[0]));
  await emit(path.join(directory, 'i18n.js'), i18n);
  for (const file of ['appearance.js', 'appearance.css']) {
    await emit(path.join(directory, file), await readFile(path.join(root, 'shared', file)));
  }
  for (const assetGroup of ['material', 'fonts']) {
    const expected = new Set(await readdir(path.join(root, 'shared/assets', assetGroup)));
    for (const file of expected) {
      await emit(path.join(directory, 'assets', assetGroup, file), await readFile(path.join(root, 'shared/assets', assetGroup, file)));
    }
    // These two namespaces are wholly generated, unlike the app's other assets.
    for (const file of await readdir(path.join(directory, 'assets', assetGroup)).catch(error => { if (error.code === 'ENOENT') return []; throw error; })) {
      if (expected.has(file)) continue;
      if (checkOnly) throw new Error(`Orphaned shared asset: ${path.relative(root, path.join(directory, 'assets', assetGroup, file))}`);
      orphans.push(path.join(directory, 'assets', assetGroup, file));
    }
  }
}
for (const [name, app] of [['cti', 'CTI_API'], ['portal', 'Portal_API'], ['call-history', 'CallHistory_API']]) {
  await emit(path.join(root, 'docs', name, 'messages.js'), generated(app));
}
for (const app of ['CTI_API', 'Portal_API', 'CallHistory_API', 'landing']) {
  await emit(path.join(root, app, 'src/server-safety.cjs'), await readFile(path.join(root, 'shared/server-safety.cjs')));
}
// A missing late input must leave every generated surface untouched. Only after
// preflight completes do we replace complete files and prune owned namespaces.
for (const { file, expected } of writes) {
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.tmp`;
  try { await writeFile(temporary, expected); await rename(temporary, file); }
  finally { await rm(temporary, { force: true }); }
}
for (const file of orphans) await rm(file, { recursive: true, force: true });
console.log(`${checkOnly ? 'Verified' : 'Synced'} ${Object.keys(messages).length} messages and shared appearance across ${targets.length} surfaces.`);
